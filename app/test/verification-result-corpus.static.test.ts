import { readdirSync, readFileSync } from "node:fs"
import path from "node:path"
import { fileURLToPath } from "node:url"

import { describe, expect, test } from "vitest"

import {
  KNOWN_ADVISORY_FINDING_TYPES,
  KNOWN_BLOCKING_FINDING_TYPES,
  advisoryFindings,
  blockingFindings,
  verificationResultSchema,
} from "@/lib/verifications/result"

/**
 * The cross-language corpus guard for the verification-result artifact
 * (task 9.1; Requirements 25.5, 25.6, 25.8, 36.3).
 *
 * Python writes this artifact and zod reads it, so proving the two agree needs
 * both languages. `agent/tests/test_verify_findings.py` **writes** a corpus into
 * `agent/tests/fixtures/verification/` covering every declared finding type and
 * every structural variation `verify/findings.py` can emit; this suite
 * **parses** every file in it with `verificationResultSchema` — the same schema
 * the internal callback route uses at the real boundary.
 *
 * Neither half proves anything alone. A field the writer emits and this reader
 * rejects fails here, at commit time, rather than as an unparseable artifact in
 * a route handler during a real run — which is the failure this pairing exists
 * to prevent, because by then the document has already been rendered and the
 * run has already spent its Azure calls.
 *
 * The corpus is regenerated by the Python suite on every run rather than
 * hand-maintained, so it cannot drift from the builder that produces it. If a
 * change to `findings.py` alters the wire shape, `git diff` shows exactly what
 * this reader will now have to accept.
 *
 * This suite parses files rather than reimplementing the writer, and asserts
 * non-vacuity twice: an absent corpus and an empty one are the same hole, and
 * "every document parsed cleanly" is a worthless claim over zero documents.
 */

const appRoot = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..")
const CORPUS_DIR = path.resolve(
  appRoot,
  "..",
  "agent",
  "tests",
  "fixtures",
  "verification",
)

/** Every declared type, mirrored from `result.ts`'s documentation arrays. */
const ALL_DECLARED_TYPES: ReadonlySet<string> = new Set<string>([
  ...KNOWN_BLOCKING_FINDING_TYPES,
  ...KNOWN_ADVISORY_FINDING_TYPES,
])

function corpusFiles(): string[] {
  let entries: string[]
  try {
    entries = readdirSync(CORPUS_DIR)
  } catch {
    // An absent directory is the same hole as an empty one: report it as a
    // missing corpus rather than letting `describe.each([])` register nothing
    // and the file report green.
    return []
  }
  return entries.filter((name) => name.endsWith(".json")).sort()
}

const files = corpusFiles()

describe("the verification-result corpus exists and is not vacuous", () => {
  test("the Python suite has written a corpus", () => {
    expect(
      files.length,
      `no .json files under ${CORPUS_DIR} — run the agent suite ` +
        `(agent/.venv/bin/pytest tests/test_verify_findings.py) to regenerate it`,
    ).toBeGreaterThanOrEqual(9)
  })

  test("it covers every declared finding type", () => {
    const seen = new Set<string>()
    for (const name of files) {
      const parsed = verificationResultSchema.parse(
        JSON.parse(readFileSync(path.join(CORPUS_DIR, name), "utf8")),
      )
      for (const finding of parsed.findings) seen.add(finding.type)
    }
    const missing = [...ALL_DECLARED_TYPES].filter((t) => !seen.has(t)).sort()
    expect(missing, "declared types no corpus document exercises").toEqual([])
  })

  test("it covers both a passing and a failing result", () => {
    const statuses = new Set(
      files.map(
        (name) =>
          verificationResultSchema.parse(
            JSON.parse(readFileSync(path.join(CORPUS_DIR, name), "utf8")),
          ).status,
      ),
    )
    expect([...statuses].sort()).toEqual(["fail", "pass"])
  })
})

describe.each(files)("%s parses as a verification result", (name) => {
  const raw: unknown = JSON.parse(
    readFileSync(path.join(CORPUS_DIR, name), "utf8"),
  )

  test("verificationResultSchema accepts it", () => {
    const parsed = verificationResultSchema.safeParse(raw)
    expect(
      parsed.success ? null : JSON.stringify(parsed.error.issues, null, 2),
    ).toBeNull()
  })

  test("severity partitions the findings exhaustively", () => {
    // Req 39.10 — classification travels on the finding, so every finding lands
    // in exactly one of the two buckets without a lookup table this side.
    const parsed = verificationResultSchema.parse(raw)
    expect(
      blockingFindings(parsed).length + advisoryFindings(parsed).length,
    ).toBe(parsed.findings.length)
  })

  test("status agrees with the observed blocking count, not the truncated list", () => {
    // The writer caps `findings` at 1,000 while `counts` keeps the true total, so
    // a document may legitimately carry fewer findings than it observed. Status
    // must follow the count.
    const parsed = verificationResultSchema.parse(raw)
    const observed = parsed.counts.blocking_findings_observed
    if (typeof observed === "number") {
      expect(parsed.status).toBe(observed > 0 ? "fail" : "pass")
    }
  })

  test("no quoted excerpt exceeds the writer's bound", () => {
    // Req 36.3. `result.ts` deliberately does not restate the 200-character bound
    // (it validates shape, not the agent's invariant), so it is asserted here
    // against the corpus instead — where a regression in the writer shows up as a
    // failing test rather than as an oversized string nothing rejects.
    const parsed = verificationResultSchema.parse(raw)
    for (const finding of parsed.findings) {
      for (const field of ["formatted", "expected", "observed", "substring"] as const) {
        const value = finding[field]
        if (typeof value === "string") {
          expect(value.length, `${name}: ${finding.type}.${field}`).toBeLessThanOrEqual(200)
        }
      }
      if (typeof finding.message === "string") {
        expect(finding.message.length).toBeLessThanOrEqual(2000)
      }
    }
  })
})
